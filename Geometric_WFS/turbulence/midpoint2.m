function [phasescreen] = midpoint2(D_ro, no_increases, initial_screen)
% [PHASESCREEN] = MIDPOINT(D_RO, NO_INCREASES);
% This function generates a kolmogorov phase screen
% using the midpoint displacement method.  The initial
% starting screen is of size 2 by 2.  The final size of 
% the phase screen is determined by the NO_INCREASES
% specified.  If NO_INCREASES = 1, the final size is 5, 
% 2 produces a final size of 9 and so on.
% Usage: result = midpoint(20, 5);
% Created By: Cressida Harding and Rachel Johnston

start_time = cputime;

matrix_size = size(initial_screen, 1);


%Initialising variables that are going to be used inside the 
%loop.
old = initial_screen;

%Increasing the size of the phase screen each loop
%The centre points are interpolated from four points and
%a random number with the correct variance.  The edge
%points are interpolated from tow points and a random 
%number with the correct variance.
for counter = 1:(no_increases+1);
	old_matrix_size = matrix_size;
	matrix_size = matrix_size*2 - 1;
	new = zeros(matrix_size);
	
	for ctr = 1 : old_matrix_size
		for ctr2 = 1:old_matrix_size
			new(ctr*2-1,ctr2*2-1) = old(ctr,ctr2);
		end
	end
	
	%Generating the distances between the new points and
	%the corresponding variances for centre and edge points.
	rhat = 1/(size(new,1) - 1);
	deltar = 1/(size(new,1) - 1);
	var4 = 0.6091*(rhat^(5/3));
	var2 = 0.4471*(deltar^(5/3));
	
	points = matrix_size - 1;
	for row = 2:2:points
		for col = 2:2:points
			new(row,col) = (new((row-1),(col-1)) + new((row-1),(col+1)) + new((row + 1), (col - 1)) + new((row + 1), (col + 1)))/4 + sqrt(var4)*randn(1,1);
		end
	end
	
	for row = 1: matrix_size
		for col = 1:matrix_size
			if new(row, col) == 0
				if row == 1
					new(row,col) = (new(row, (col - 1)) +  new(row, (col + 1)))/2 + sqrt(var2)*randn(1,1);
					%Left and right
				elseif col == 1
					new(row, col) = (new((row - 1), col) + new((row + 1), col))/2 + sqrt(var2)*randn(1,1);
					%Top and Bottom	 
				elseif row == matrix_size
					new(row,col) = (new(row, (col-1)) +  new(row, (col + 1)))/2 + sqrt(var2)*randn(1,1);
					%Left and Right 	
				elseif col == matrix_size
					%Top and Bottom
					new(row, col) = (new((row - 1), col) + new((row + 1), col))/2 + sqrt(var2)*randn(1,1);
				else
					%Four corners
					new(row,col) = (new((row),(col-1)) + new((row-1),(col)) + new((row + 1), (col )) + new((row ), (col + 1)))/4 + sqrt(var4)*randn(1,1);
				end
			end
		end	
	end			
	
	old = new;
end			


%The phase screen was calculated with D/ro = 1.
%The D/ro is introduced here by multiplying the 
%phase screen generated by (D/ro)^(5/6);
phasescreen = old * ((D_ro)^(5/6));

elapsed_time = cputime - start_time

