constellations = [[
    ((17,4,36.3),(-19,41,25.6)),
    ((17,4,35.5),(-19,41,50.9)),
    ((17,4,40.1),(-19,41,56.3)),
    ((17,4,40.4),(-19,42,36.8)),
    ((17,4,38.1),(-19,42,34.0))]
]

def get_natural():
    cons_degs = []
    for constellation in constellations:
        con = []
        s0 = 0
        s1 = 0
        for ra, dec in constellation:
            hours = ra[0] + ra[1] / 60 + ra[2] / 3600
            if dec[0] > 0:
                degs = dec[0] + dec[1] / 60 + dec[2] / 3600
            else:
                degs = dec[0] - dec[1] / 60 - dec[2] / 3600
            s = (hours*15*np.pi/180, degs*np.pi/180)
            con.append(s)
            s0 += s[0]
            s1 += s[1]
        s0 /= len(con)
        s1 /= len(con)
        cons = []
        for s in con:
            ra = s[0]-s0
            dec= s[1]-s1
            gamma = np.sqrt(ra*ra+dec*dec)
            theta = np.arctan2(dec, ra)
            cons.append((theta, gamma))
        cons_degs.append(cons)
    return cons_degs

